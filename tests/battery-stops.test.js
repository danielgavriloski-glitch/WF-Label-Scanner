'use strict';
const assert=require('assert');
const fs=require('fs');
const read=p=>fs.readFileSync(p,'utf8');
const route=read('app/src/main/java/mk/workfashion/personal/RouteTrackingService.java');
const arrival=read('app/src/main/java/mk/workfashion/personal/WorkdayArrivalService.java');
const nativeMap=read('app/src/main/java/mk/workfashion/personal/RouteMapActivity.java');
const ui=read('app/src/main/assets/v12-ui.js');
const vehicle=read('app/src/main/assets/vehicle-core.js');
const bridge=read('app/src/main/java/mk/workfashion/personal/MainActivity.java');

assert(route.includes('STOP_MS=10L*60L*1000L'),'stop threshold must be 10 minutes');
assert(route.includes('SAMPLE_INTERVAL_MS=2L*60L*1000L'),'stop sampling must be at least minutes apart');
assert(route.includes('requestSingleUpdate(LocationManager.NETWORK_PROVIDER'),'use isolated cheap location fixes');
assert(route.includes('requestSingleUpdate(LocationManager.GPS_PROVIDER'),'use GPS fallback fixes');
assert(!route.includes('requestLocationUpdates('),'never keep full-time route GPS running');
const locationHandler=route.slice(route.indexOf('@Override public void onLocationChanged'),route.indexOf('private void updateStopState('));
assert(!locationHandler.includes('points.put('),'do not append sampled route points');
assert(!locationHandler.includes('distanceM'),'do not record automatic kilometres');
assert(!locationHandler.includes('queueCompaction'),'never road-match new stops');
assert(ui.includes('Застанување над 10 минути'),'UI must say 10 minutes');
assert(!ui.includes('подолго од 5 минути')&&!ui.includes('над 5 минути'),'no stale 5 minute threshold');
assert(!ui.includes('routeKm('),'no automatic kilometre UI');
assert(!ui.includes('<polyline'),'no polyline in WebView');
const mapLayer=nativeMap.slice(nativeMap.indexOf('private RouteBounds addRouteLayers('),nativeMap.indexOf('private void addRouteSegment(',nativeMap.indexOf('private RouteBounds addRouteLayers(')));
assert(!mapLayer.includes('addRouteSegment('),'offline map must show stops but not roads or route lines');
assert(mapLayer.includes('session.optJSONArray("stops")'),'offline map must retain stop markers');
assert(arrival.includes('return todaySession==null||todaySession.optLong("startAt",0L)<=0'),'disable auto-arrival tracking after workday started');
assert(arrival.includes('requestSingleUpdate(LocationManager.NETWORK_PROVIDER'),'workday arrival must use interval checks');
assert(!arrival.includes('requestLocationUpdates('),'workday arrival GPS must not run continuously');
assert(vehicle.includes('if(!Number.isFinite(recordedKm)||recordedKm<=0)continue'),'stop-only trips must not create 0km vehicle entries');
assert(bridge.includes('displayStateJson(MainActivity.this)'),'WebView must not load raw points for every render');
assert(route.includes('public static String stateJson(Context c){return readState(c).toString();}'),'full native backup must remain');
console.log('OK WFAG battery stop-only regression checks');
