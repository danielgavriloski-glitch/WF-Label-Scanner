'use strict';
const assert=require('assert');
const Core=require('../app/src/main/assets/core.js');
const Warehouse=require('../app/src/main/assets/documents-core.js');
const Pickups=require('../app/src/main/assets/pickups-core.js');
const clone=x=>JSON.parse(JSON.stringify(x));
const at=new Date('2026-11-20T10:15:00Z');
let state=Core.fresh(at);
const original=JSON.stringify(state);
Core.validate(state);
assert.equal(JSON.stringify(state),original,'legacy state must not be migrated on read');
assert.equal(Pickups.pending().length,0);
assert.throws(()=>Pickups.put(null,{from:'',goods:'3 пакети'},at));
assert.throws(()=>Pickups.put(null,{from:'Јуба',goods:'  '},at));
let result=Pickups.put(null,{from:' Јуба ',goods:' 3 пакети текстил ',address:'Скопје',note:'Контакт на магацин'},at);
const firstId=result.item.id;
state.pickupLog=result.log;
assert.equal(result.item.from,'Јуба');
result=Pickups.put(state.pickupLog,{from:'Про Унион',goods:'Испратница'},at);
state.pickupLog=result.log;
const secondId=result.item.id;
assert.equal(Pickups.pending(state.pickupLog).length,2);
assert.equal(state.warehouseLog,undefined,'pending goods must not appear as completed documents');
const saved=JSON.stringify(state);
const done=Pickups.complete(state,firstId,at);
assert.equal(JSON.stringify(state),saved,'completion must not mutate uncommitted state');
assert.equal(Pickups.pending(done.state.pickupLog).length,1);
assert.equal(done.state.warehouseLog.visits.length,1);
const visit=done.state.warehouseLog.visits[0];
assert.equal(visit.warehouseName,'Јуба');assert.equal(visit.action,'pickup');
assert(visit.note.includes('3 пакети текстил')&&visit.note.includes('Скопје')&&visit.note.includes('Контакт на магацин'));
assert.equal(done.state.pickupLog.items[0].visitId,visit.id);
const repeat=Pickups.complete(done.state,firstId,new Date('2026-11-21T10:00:00Z'));
assert.equal(repeat.changed,false);assert.equal(repeat.state.warehouseLog.visits.length,1);
assert.deepEqual(repeat.state,done.state,'double tap must not create duplicate documents');
assert.throws(()=>Pickups.put(done.state.pickupLog,{id:firstId,from:'A',goods:'B'},at));
assert.throws(()=>Pickups.complete(done.state,'missing',at));
state=Pickups.complete(done.state,secondId,at).state;
assert.equal(Pickups.pending(state.pickupLog).length,0);
assert.equal(state.warehouseLog.visits.length,2);
assert.deepEqual(Core.validate(JSON.parse(JSON.stringify(state))),state,'backup and restart retain completed status');
const attachment={id:'document_test',fileId:'abcdef.jpg',name:'Испратница.jpg',mime:'image/jpeg',bytes:100,sha256:'a'.repeat(64)};
state.warehouseLog.visits[0].documents.push(attachment);
const old=Core.fresh(at),beforeImport=JSON.stringify(old);
const restored=Pickups.preserveOnImport(state,old);
assert.equal(JSON.stringify(old),beforeImport);
assert.equal(restored.pickupLog.items.length,2);
assert.equal(restored.warehouseLog.visits.length,2);
assert.deepEqual(restored.warehouseLog.visits[0].documents,[attachment],'old backups must retain linked attachments');
assert.deepEqual(Pickups.preserveOnImport(state,state),state,'a full backup restores its own pickups');
const oldWithDocs=clone(state);delete oldWithDocs.pickupLog;
assert.equal(Pickups.preserveOnImport(state,oldWithDocs).warehouseLog.visits.length,2);
const conflict=clone(oldWithDocs);conflict.warehouseLog.visits[0].note='Different';
assert.throws(()=>Pickups.preserveOnImport(state,conflict),'conflicting linked visits must not be silently replaced');
const pendingOnly=Core.fresh(at);pendingOnly.pickupLog=result.log;
assert.equal(Pickups.pending(Pickups.preserveOnImport(pendingOnly,old).pickupLog).length,2);
for(const modify of [s=>s.pickupLog.items[0].status='unknown',s=>s.pickupLog.items[0].from='',s=>s.pickupLog.items[0].goods='x'.repeat(2001),s=>s.pickupLog.items[0].pickedAt='bad',s=>s.pickupLog.items.push(clone(s.pickupLog.items[0])),s=>s.warehouseLog.visits=[]]){
 const bad=clone(state);modify(bad);assert.throws(()=>Core.validate(bad));
}
assert.equal(Warehouse.filter(state.warehouseLog,{query:'текстил',action:'pickup'}).length,1);
console.log('WFAG_PICKUPS_OK: pending entries, atomic document transfer, double-tap safety, restart, full/legacy backup, linked attachments, validation');
