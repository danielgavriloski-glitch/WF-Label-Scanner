'use strict';
const assert=require('assert');
const Core=require('../app/src/main/assets/core.js');
require('../app/src/main/assets/v12-core.js');
require('../app/src/main/assets/workday-integration.js');
const W=require('../app/src/main/assets/workday-core.js');
const at=(date,h,m=0)=>Core.timestamp(date,String(h).padStart(2,'0')+':'+String(m).padStart(2,'0'));
const date='2026-11-11';
const state=Core.fresh(new Date(at(date,8)));
state.settings.trackStart='2026-11-01';
const now=new Date(at(date,18));
const before=Core.week(state,Core.weekStart(date),now).rows.find(r=>r.date===date);
assert.strictEqual(before.worked,480);
let d=W.start(W.newDay(date),at(date,8));
d=W.depart(d,at(date,9));d=W.arrive(d,at(date,10));
d=W.finish(d,at(date,17));
state.workdaySessions={[date]:d};
Core.validate(state);
const week=Core.week(state,Core.weekStart(date),now);
const row=week.rows.find(r=>r.date===date);
assert.strictEqual(row.worked,540);
assert.strictEqual(row.travel,60);
assert.strictEqual(row.overtime,60);
assert.strictEqual(row.shortfall,0);
const short=JSON.parse(JSON.stringify(state));
short.workdaySessions[date]=W.finish(W.start(W.newDay(date),at(date,8)),at(date,14));
const rowShort=Core.week(short,Core.weekStart(date),now).rows.find(r=>r.date===date);
assert.strictEqual(rowShort.worked,360);
assert.strictEqual(rowShort.shortfall,120);
assert.strictEqual(rowShort.overtimeNet,-120);
const open=JSON.parse(JSON.stringify(state));
open.workdaySessions[date]=W.start(W.newDay(date),at(date,8));
assert.strictEqual(Core.week(open,Core.weekStart(date),new Date(at(date,12))).rows.find(r=>r.date===date).shortfall,0);
const pending=JSON.parse(JSON.stringify(state));
delete pending.workdaySessions;
pending.workdaySettings={mode:'geofence',start:'08:00',radiusM:100,workplace:{lat:41.998,lon:21.425},activatedOn:date};
const notThere=Core.day(pending,date,new Date(at(date,12)));
assert.strictEqual(notThere.worked,0,'GPS work must not earn hours before arriving');
assert.strictEqual(notThere.workdayPending,true);
const legacy=Core.day(pending,'2026-11-10',now);
assert.strictEqual(legacy.worked,480,'legacy schedule before activation must remain intact');
const saturday='2026-11-14';
const weekendState=JSON.parse(JSON.stringify(state));
weekendState.workdaySessions={[saturday]:W.finish(W.start(W.newDay(saturday),at(saturday,9)),at(saturday,13))};
const weekend=Core.week(weekendState,Core.weekStart(saturday),new Date(at(saturday,18))).rows.find(r=>r.date===saturday);
assert.strictEqual(weekend.worked,240);
assert.strictEqual(weekend.overtime,240,'weekend work must count as overtime');
console.log('WFAG workday integration: all tests passed');
