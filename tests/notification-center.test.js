'use strict';
const assert=require('node:assert/strict');
const Inbox=require('../app/src/main/assets/notification-center.js');
const a={id:'pickup_1',title:'Роба за подигање',body:'Јуба\n3 пакети',createdAt:1795680000000,read:false,type:'pickup',targetId:'pickup_a'};
const b={id:'service_1',title:'Сервис',body:'Промена на масло',createdAt:a.createdAt+5000,read:true,type:'service',targetId:'service_a'};
const native={version:1,notifications:[a,b]};
const saved=JSON.stringify(native);
assert.deepEqual(Inbox.normalize(saved).notifications.map(x=>x.id),['service_1','pickup_1']);
assert.equal(Inbox.unread(saved),1);
const read=Inbox.readCopy(saved,'pickup_1');
assert.equal(Inbox.unread(JSON.stringify(read)),0,'read state survives serialization and restart');
assert.equal(JSON.stringify(native),saved,'reading must not mutate native backup data');
assert.equal(Inbox.readCopy(saved,'missing').notifications.length,2,'unknown notification never creates a row');
assert.equal(Inbox.unread(Inbox.readCopy(saved,'')),0,'mark all read applies to both notice kinds');
const old={version:1,items:[{id:'old',kind:'pickup',title:'Old',body:'Body',createdAt:a.createdAt,readAt:a.createdAt+1,recordId:'cargo_1',target:'pickups'}]};
assert.equal(Inbox.normalize(old).notifications[0].type,'pickup');
assert.equal(Inbox.normalize(old).notifications[0].targetId,'cargo_1');
assert.equal(Inbox.unread(old),0);
assert.equal(Inbox.normalize({notifications:[a,{...a,read:true}]}).notifications.length,1,'same actual delivery is not duplicated');
assert.equal(Inbox.unread({notifications:[a,{...a,read:true}]}),0,'duplicate restored copies retain read state');
assert.deepEqual(Inbox.normalize(null),{version:1,notifications:[]},'empty history must not manufacture notifications');
assert.throws(()=>Inbox.normalize('{broken'));
assert.throws(()=>Inbox.normalize({notifications:[{...a,createdAt:'invalid'}]}));
assert.equal(Inbox.parseOpened('pickup_1'),'pickup_1');
assert.equal(Inbox.parseOpened(JSON.stringify(a)),'pickup_1');
assert.equal(Inbox.parseOpened(a),'pickup_1');
console.log('WFAG_NOTIFICATION_CENTER_OK: real history, chronology, read/restart, native schema compatibility, no fabricated entries');
