'use strict';
const assert=require('node:assert/strict');
const Core=require('../app/src/main/assets/core.js');
const Warehouse=require('../app/src/main/assets/documents-core.js');
const Pickups=require('../app/src/main/assets/pickups-core.js');
const now=new Date('2026-11-26T12:00:00Z');
const copy=x=>JSON.parse(JSON.stringify(x));
const base=Core.fresh(now);
base.settings.name='Даниел';
const v=Warehouse.putVisit(null,{date:'2026-11-20',time:'12:30',warehouseId:'',warehouseName:'Про Унион',action:'pickup',note:'Оригинален документ',stopId:'',sessionId:''});
v.visit.documents.push({id:'attachment_1',fileId:'original.jpg',name:'Испратница.jpg',mime:'image/jpeg',bytes:123,sha256:'a'.repeat(64)});
base.warehouseLog=v.log;
const shipment=(id,status,extras={})=>({id,status,company:'Јуба',goods:'Текстил',location:'Скопје',dueDate:'2026-11-26',packages:10,pickedPackages:status==='partial'?3:status==='pending'?0:10,weightKg:120.5,notes:'Белешка '.repeat(500),documents:['attachment_1'],warehouseId:'',visitIds:[],createdAt:'2026-11-19T10:00:00Z',updatedAt:'2026-11-20T10:00:00Z',...extras});
base.cargoLog={version:1,shipments:[shipment('cargo_partial','partial'),shipment('cargo_done','delivered',{visitIds:[v.visit.id]}),shipment('cargo_cancel','cancelled'),shipment('cargo_unlinked','picked_up')]};
base.customFutureField={keep:true};
const before=JSON.stringify(base);
let migrated=Pickups.migrate(base);
Core.validate(migrated);
assert.equal(JSON.stringify(base),before,'migration must not mutate source backup');
assert.equal(migrated.pickupLog.items.length,2,'unlinked completed/cancelled goods stay in raw archive without fabricated documents');
assert.equal(migrated.cargoLog.shipments.length,4);
assert.equal(migrated.warehouseLog.visits.length,1,'linked completed goods must reuse their document');
assert.deepEqual(migrated.warehouseLog.visits[0].documents,v.visit.documents);
assert.deepEqual(migrated.customFutureField,{keep:true});
assert.equal(migrated.pickupLog.items[0].note.length,4000,'full older notes survive');
assert.equal(migrated.pickupLog.items[0].pickedPackages,3);
assert.equal(migrated.pickupLog.items[0].weightKg,120.5);
assert.deepEqual(Pickups.migrate(migrated),migrated,'reopen/import migration is idempotent');
const partial=migrated.pickupLog.items.find(x=>x.legacyCargoId==='cargo_partial');
let step=Pickups.collect(migrated,partial.id,2,now);
assert.equal(step.partial,true);assert.equal(step.state.warehouseLog.visits.length,1);
assert.equal(step.state.pickupLog.items[0].pickedPackages,5);
assert.equal(step.state.cargoLog.shipments[0].pickedPackages,5);
step=Pickups.collect(step.state,partial.id,5,now);
assert.equal(step.state.warehouseLog.visits.length,2);
assert.equal(step.state.cargoLog.shipments[0].status,'picked_up');
assert.equal(step.state.pickupLog.items[0].note.length,4000);
assert.equal(Pickups.complete(step.state,partial.id,now).changed,false,'double tap cannot add another document');
const delivered=Pickups.deliver(step.state,partial.id,now);
assert.equal(delivered.cargoLog.shipments[0].status,'delivered');
assert.equal(Pickups.syncLegacy(delivered).cargoLog.shipments[0].status,'delivered','later saves retain delivered state');
const old=Core.fresh(now);
const restored=Pickups.preserveOnImport(delivered,old);
assert.equal(restored.pickupLog.items.length,2);
assert.equal(restored.cargoLog.shipments.length,4);
assert.equal(restored.warehouseLog.visits.length,2);
assert.deepEqual(restored.warehouseLog.visits.find(x=>x.id===v.visit.id).documents,v.visit.documents);
const shared=copy(base);shared.cargoLog.shipments.push(shipment('cargo_shared','picked_up',{visitIds:[v.visit.id]}));
const sharedRestored=Pickups.migrate(shared);Core.validate(sharedRestored);
assert.equal(sharedRestored.warehouseLog.visits.length,1,'two legacy cargos sharing one visit never duplicate attachments');
const broken=copy(base);broken.cargoLog.shipments[0].pickedPackages=11;
assert.throws(()=>Pickups.migrate(broken),'bad older goods must be reported, not silently dropped');
const empty=copy(base);empty.cargoLog.shipments[0].goods='';
assert.equal(Pickups.migrate(empty).cargoLog.shipments[0].goods,'','empty original description is retained');
console.log('WFAG_PICKUPS_LEGACY_OK: lossless/idempotent cargo migration, existing attachments, partial pickup, archive, restore and no duplicated documents');
